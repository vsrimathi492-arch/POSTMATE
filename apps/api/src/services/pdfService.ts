import PDFDocument from 'pdfkit';
import { DailyOperationsReport } from '@postmate/shared';

export class PdfService {
  static generateDailyReport(report: DailyOperationsReport): Promise<Buffer> {
    return new Promise((resolve, reject) => {
      const doc = new PDFDocument({ margin: 40, size: 'A4' });
      const buffers: Buffer[] = [];

      doc.on('data', chunk => buffers.push(chunk));
      doc.on('end', () => resolve(Buffer.concat(buffers)));
      doc.on('error', err => reject(err));

      // Header Banner
      doc.rect(40, 40, 515, 60).fill('#0b1d3a');
      doc.fillColor('#ffffff').fontSize(18).text('POSTMATE', 55, 52);
      doc.fontSize(10).text('Smart Postal Operations Management System', 55, 74);
      doc.fontSize(9).text(`OFFICIAL ${report.reportType.replace(/_/g, ' ')} REPORT`, 260, 56, { align: 'right', width: 280 });
      doc.text(`Date: ${report.reportDate}`, 320, 72, { align: 'right', width: 220 });

      doc.moveDown(3);

      // Office Info Table
      doc.fillColor('#1e293b').fontSize(12).text('1. Office & Verification Details', 40, 115, { underline: true });
      doc.fontSize(9).fillColor('#334155');
      doc.text(`Office Name: ${report.officeName} (${report.officeCode})`, 40, 135);
      doc.text(`Report Date: ${report.reportDate}`, 40, 150);
      doc.text(`Generated By: ${report.generatedByName} at ${new Date(report.generatedAt).toLocaleTimeString()}`, 300, 135);
      doc.text(`Approval Status: ${report.isApproved ? 'APPROVED BY ' + report.approvedByName : 'PENDING POSTMASTER APPROVAL'}`, 300, 150);

      // Horizontal Divider
      doc.moveTo(40, 170).lineTo(555, 170).stroke('#cbd5e1');

      // Mail Operations Summary
      doc.fontSize(12).fillColor('#1e293b').text('2. Mail Operations Summary', 40, 185, { underline: true });
      doc.fontSize(9).fillColor('#334155');

      const mailY = 205;
      doc.rect(40, mailY, 120, 45).fillAndStroke('#f8fafc', '#e2e8f0');
      doc.fillColor('#64748b').fontSize(8).text('INCOMING MAIL', 45, mailY + 6);
      doc.fillColor('#0b1d3a').fontSize(16).text(`${report.mailSummary.totalIncoming}`, 45, mailY + 20);

      doc.rect(170, mailY, 120, 45).fillAndStroke('#f8fafc', '#e2e8f0');
      doc.fillColor('#64748b').fontSize(8).text('OUTGOING MAIL', 175, mailY + 6);
      doc.fillColor('#0b1d3a').fontSize(16).text(`${report.mailSummary.totalOutgoing}`, 175, mailY + 20);

      doc.rect(300, mailY, 120, 45).fillAndStroke('#f8fafc', '#e2e8f0');
      doc.fillColor('#64748b').fontSize(8).text('PROCESSED & SORTED', 305, mailY + 6);
      doc.fillColor('#0b1d3a').fontSize(16).text(`${report.mailSummary.totalSorted}`, 305, mailY + 20);

      doc.rect(430, mailY, 120, 45).fillAndStroke('#f8fafc', '#e2e8f0');
      doc.fillColor('#64748b').fontSize(8).text('PENDING SORTING', 435, mailY + 6);
      doc.fillColor('#d97706').fontSize(16).text(`${report.mailSummary.pendingSorting}`, 435, mailY + 20);

      // Category Breakdown Subtable
      doc.fontSize(9).fillColor('#334155');
      const catY = 260;
      doc.text(`Speed Post: ${report.mailSummary.categoryBreakdown.speedPost}`, 45, catY);
      doc.text(`Registered Post: ${report.mailSummary.categoryBreakdown.registeredPost}`, 175, catY);
      doc.text(`Parcels: ${report.mailSummary.categoryBreakdown.parcel}`, 305, catY);
      doc.text(`Ordinary Letters: ${report.mailSummary.categoryBreakdown.ordinaryLetter}`, 435, catY);

      // Horizontal Divider
      doc.moveTo(40, 280).lineTo(555, 280).stroke('#cbd5e1');

      // Delivery Summary
      doc.fontSize(12).fillColor('#1e293b').text('3. Delivery Operations Summary', 40, 295, { underline: true });
      const delY = 315;

      doc.rect(40, delY, 120, 45).fillAndStroke('#f8fafc', '#e2e8f0');
      doc.fillColor('#64748b').fontSize(8).text('TOTAL ASSIGNED', 45, delY + 6);
      doc.fillColor('#0b1d3a').fontSize(16).text(`${report.deliverySummary.totalAssignedForDelivery}`, 45, delY + 20);

      doc.rect(170, delY, 120, 45).fillAndStroke('#f8fafc', '#e2e8f0');
      doc.fillColor('#64748b').fontSize(8).text('DELIVERED TODAY', 175, delY + 6);
      doc.fillColor('#059669').fontSize(16).text(`${report.deliverySummary.deliveredToday}`, 175, delY + 20);

      doc.rect(300, delY, 120, 45).fillAndStroke('#f8fafc', '#e2e8f0');
      doc.fillColor('#64748b').fontSize(8).text('EXCEPTIONS', 305, delY + 6);
      doc.fillColor('#dc2626').fontSize(16).text(`${report.deliverySummary.deliveryExceptions}`, 305, delY + 20);

      doc.rect(430, delY, 120, 45).fillAndStroke('#f8fafc', '#e2e8f0');
      doc.fillColor('#64748b').fontSize(8).text('SUCCESS RATE', 435, delY + 6);
      doc.fillColor('#0b1d3a').fontSize(16).text(`${report.deliverySummary.deliverySuccessRate}%`, 435, delY + 20);

      // Horizontal Divider
      doc.moveTo(40, 370).lineTo(555, 370).stroke('#cbd5e1');

      // Cashbook Summary
      doc.fontSize(12).fillColor('#1e293b').text('4. Cashbook & Accounts Summary', 40, 385, { underline: true });
      const cashY = 405;

      doc.fontSize(9).fillColor('#334155');
      doc.text(`Opening Balance: Rs. ${report.cashSummary.openingBalance.toFixed(2)}`, 45, cashY);
      doc.text(`Total Receipts: Rs. ${report.cashSummary.totalReceipts.toFixed(2)}`, 45, cashY + 18);
      doc.text(`Total Payments: Rs. ${report.cashSummary.totalPayments.toFixed(2)}`, 300, cashY);
      doc.text(`Calculated Closing Balance: Rs. ${report.cashSummary.calculatedClosingBalance.toFixed(2)}`, 300, cashY + 18);

      const statusColor = report.cashSummary.isReconciled ? '#059669' : '#d97706';
      doc.fillColor(statusColor).fontSize(10).text(
        `Reconciliation Status: ${report.cashSummary.isReconciled ? 'VERIFIED & RECONCILED' : 'PENDING VERIFICATION'}`,
        45, cashY + 40
      );

      // Horizontal Divider
      doc.moveTo(40, 470).lineTo(555, 470).stroke('#cbd5e1');

      // Staff Workload Summary
      doc.fontSize(12).fillColor('#1e293b').text('5. Staff Workload & Duty Allocation', 40, 485, { underline: true });
      doc.fontSize(8).fillColor('#64748b');
      doc.text('STAFF NAME', 45, 505);
      doc.text('ROLE', 200, 505);
      doc.text('ASSIGNED', 340, 505);
      doc.text('COMPLETED', 450, 505);

      let rowY = 520;
      report.staffSummary.workloadDistribution.slice(0, 5).forEach(s => {
        doc.fillColor('#334155').fontSize(9);
        doc.text(s.staffName, 45, rowY);
        doc.text(s.role, 200, rowY);
        doc.text(`${s.assigned}`, 340, rowY);
        doc.text(`${s.completed}`, 450, rowY);
        rowY += 15;
      });

      // Signature Box
      const sigY = 660;
      doc.rect(40, sigY, 230, 60).stroke('#cbd5e1');
      doc.fontSize(8).fillColor('#64748b').text('PREPARED BY (POSTAL STAFF)', 45, sigY + 6);
      doc.fillColor('#0b1d3a').fontSize(10).text(report.generatedByName, 45, sigY + 38);

      doc.rect(325, sigY, 230, 60).stroke('#cbd5e1');
      doc.fontSize(8).fillColor('#64748b').text('VERIFIED & APPROVED BY (POSTMASTER)', 330, sigY + 6);
      if (report.isApproved && report.approvedByName) {
        doc.fillColor('#059669').fontSize(10).text(`Approved: ${report.approvedByName}`, 330, sigY + 38);
      } else {
        doc.fillColor('#94a3b8').fontSize(9).text('Signature & Official Seal Pending', 330, sigY + 38);
      }

      // Footer
      doc.fontSize(7).fillColor('#94a3b8').text(
        'POSTMATE - Smart Postal Operations Management System. Single-Source-of-Truth Architecture. Independent Prototype.',
        40, 770, { align: 'center', width: 515 }
      );

      doc.end();
    });
  }
}
